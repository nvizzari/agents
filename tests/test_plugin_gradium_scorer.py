"""Tests for the Gradium end-of-turn scorer (`gradium.experimental.scorer`)."""

from __future__ import annotations

import json
import logging
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

import pytest

from livekit.plugins.gradium.experimental.scorer import (
    WEIGHTS_DIR,
    FallbackScorer,
    LearnedScorer,
    Scorer,
    load_scorer,
)
from livekit.plugins.gradium.experimental.signals import Step, Word

pytestmark = pytest.mark.unit

# Held-out English turns replayed against production Gradium, with the score the trained
# scikit-learn model gives at every step. Regenerated by `tools/eot/train.py export`.
FIXTURE = Path(__file__).parent / "gradium_scorer_steps.json"
BUNDLED = WEIGHTS_DIR / "default.json"
Event = list[Any]


def _bundled() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(BUNDLED.read_text())
    return data


def _model() -> str:
    return str(_bundled()["model"])


def _learned() -> LearnedScorer:
    scorer = load_scorer("default", model=_model())
    assert isinstance(scorer, LearnedScorer)
    return scorer


def _step(t: float, probs: Iterable[float]) -> Step:
    p = tuple(probs)
    return Step(audio_time=t, probs=(p[0], p[1], p[2], p[3]))


def _replay(scorer: Scorer, events: list[Event]) -> list[float]:
    """Feed fixture events (`step`, `word`, `flush`) in order; return the step scores."""
    scores = []
    audio_time = 0.0
    for kind, *args in events:
        if kind == "step":
            audio_time = args[0]
            scores.append(scorer.on_step(_step(args[0], args[1:])))
        elif kind == "word":
            scorer.on_word(Word(text=args[0], start_time=args[1]), audio_time)
        else:
            scorer.on_flush()
    return scores


def _ramp(n: int, start: float = 0.0) -> list[Event]:
    """A pause opening: probabilities rising over `n` steps of 80 ms."""
    return [
        [
            "step",
            round(start + 0.08 * (i + 1), 2),
            *(min(0.95, 0.1 + 0.08 * i * k) for k in (4, 3, 2, 1)),
        ]
        for i in range(n)
    ]


def test_learned_scorer_matches_trained_model() -> None:
    # The pure-Python evaluator must give the scores the trained model gives on real
    # recorded streams, steps after a flush included; otherwise the benchmark numbers the
    # weights were selected on do not describe what ships.
    fixture = json.loads(FIXTURE.read_text())
    assert fixture["weights"] == "default"
    scorer = _learned()
    n_flushed = 0
    for turn in fixture["turns"]:
        scorer.reset()
        got = _replay(scorer, turn["events"])
        assert got == pytest.approx(turn["expected"], abs=1e-9), turn["id"]
        n_flushed += sum(1 for e in turn["events"] if e[0] == "flush")
    assert n_flushed > 0, "the fixture must exercise the post_flush weights"


def _write(tmp_path: Path, edit: Callable[[dict[str, Any]], Any]) -> Path:
    data = _bundled()
    edit(data)
    return _text_file(tmp_path, json.dumps(data))


def _bad_tree(data: dict[str, Any]) -> None:
    tree = data["sets"]["passive"]["trees"][0]
    tree["left"][0] = 0  # a node pointing at itself would loop forever


def _text_file(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "weights.json"
    path.write_text(text)
    return path


# Each case returns the `weights` and `model` arguments to pass to `load_scorer`.
BAD_WEIGHTS: dict[str, Callable[[Path], tuple[str | Path, str | None]]] = {
    "missing file": lambda tmp: (tmp / "absent.json", None),
    "unknown bundled name": lambda tmp: ("no-such-weights", None),
    "not json": lambda tmp: (_text_file(tmp, "{nope"), None),
    "wrong format version": lambda tmp: (_write(tmp, lambda d: d.update(format=999)), None),
    "missing training delay": lambda tmp: (_write(tmp, lambda d: d.pop("delay_in_frames")), None),
    "missing weight set": lambda tmp: (_write(tmp, lambda d: d["sets"].pop("post_flush")), None),
    "unknown feature": lambda tmp: (
        _write(tmp, lambda d: d["sets"]["passive"]["features"].append("pitch")),
        None,
    ),
    "cyclic tree": lambda tmp: (_write(tmp, _bad_tree), None),
    "other server model": lambda tmp: ("default", "00000000@1"),
}


@pytest.mark.parametrize("case", BAD_WEIGHTS)
def test_unusable_weights_fall_back_with_one_warning(
    case: str, tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    # A stream must keep running on `min(p2, p3)` when its weights cannot be trusted, and
    # say so once, rather than crash or score with weights read for another model.
    weights, model = BAD_WEIGHTS[case](tmp_path)
    with caplog.at_level(logging.WARNING, logger="livekit.plugins.gradium"):
        scorer = load_scorer(weights, model=model)
    assert isinstance(scorer, FallbackScorer)
    assert len([r for r in caplog.records if r.levelno == logging.WARNING]) == 1


def test_no_weights_falls_back_silently(caplog: pytest.LogCaptureFixture) -> None:
    # `weights=None` is the user asking for the fallback: no warning to act on.
    with caplog.at_level(logging.WARNING, logger="livekit.plugins.gradium"):
        scorer = load_scorer(None)
    assert isinstance(scorer, FallbackScorer)
    assert not caplog.records


def test_fallback_is_min_of_2s_and_3s_horizons() -> None:
    # The fallback is the hand-written fusion the plan's numbers (978 ms @ 5%) refer to.
    scorer = FallbackScorer()
    assert scorer.on_step(_step(0.08, (0.9, 0.8, 0.3, 0.6))) == 0.3
    assert scorer.on_step(_step(0.16, (0.1, 0.2, 0.7, 0.4))) == 0.4


def test_turn_end_forgets_words_and_flush_but_not_audio() -> None:
    # After a committed turn, the next turn must not inherit the previous one's word count,
    # pauses or flush, while the probability history (continuous audio) is kept: the
    # next score equals that of a scorer that heard the same audio and no words.
    steps = _ramp(8)
    with_turn = _learned()
    _replay(with_turn, steps[:3])
    _replay(with_turn, [["word", "so", 0.0], ["word", "yes", 1.0], ["flush"]])
    _replay(with_turn, steps[3:6])
    assert with_turn.flushed
    with_turn.on_turn_end()
    assert not with_turn.flushed

    audio_only = _learned()
    _replay(audio_only, steps[:6])
    assert _replay(with_turn, steps[6:]) == _replay(audio_only, steps[6:])


def test_reset_forgets_everything() -> None:
    # A new connection restarts the audio clock: nothing from the old one may leak in.
    used = _learned()
    _replay(used, [*_ramp(10), ["word", "hello", 0.2], ["flush"]])
    used.reset()
    assert not used.flushed
    events = [["word", "hi", 0.0], *_ramp(6)]
    assert _replay(used, events) == _replay(_learned(), events)


def test_flush_holds_until_speech_resumes() -> None:
    # The post_flush weights apply after a flush, through the held words the flush returns,
    # and stop once a word starting after the flush shows the speaker resumed.
    scorer = _learned()
    _replay(scorer, [*_ramp(5), ["flush"], *_ramp(2, start=0.4)])
    assert scorer.flushed
    _replay(scorer, [["word", "held", 0.3]])
    assert scorer.flushed
    _replay(scorer, [["word", "again", 0.5]])
    assert not scorer.flushed
